/**
 * Phase 2 Lot 4 — the sites × platforms conversion bench (the proof of
 * objective #2 and the permanent non-regression net for later phases).
 *
 * Every SAVED source in the repo fixtures (Scraper outputs of every
 * generation, products.json, .eloshon, third-party scraping exports, supplier
 * feeds, platform exports) is converted to EACH target platform through the
 * same convert() the app runs, and every cell gets:
 *   status     failed    — the conversion produced nothing (reason = error code)
 *              n/a       — the direction does not exist or the target cannot
 *                          take this entity (reason given; not a defect)
 *              flagged   — converted, and the user is told something: a loss
 *                          the target cannot carry, or a notice (warning)
 *              preserved — converted, nothing flagged, but source data with no
 *                          canon field was kept and listed
 *              ok        — converted cleanly
 *   preserved  number of distinct source fields kept outside the canon fields
 *   flagged    number of distinct loss + warning codes raised
 *
 * scripts/bench.mjs writes docs/phase2-conversion-matrix.md and the expected
 * snapshot test/bench/expected-matrix.json; test/bench.test.mjs fails when a
 * cell regresses or the artifact no longer matches the engine.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { convert } from '../../core/dist/index.mjs';
import { loadReferenceFormatsSync } from '../../core/knowledge-proposal/reference.mjs';
import { DIRECTIONS } from '../../core/directions.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const FIX = path.join(ROOT, 'test', 'fixtures');
const read = (rel) => fs.readFileSync(path.join(FIX, rel), 'utf8');

export const TARGETS = ['shopify', 'woocommerce', 'wix', 'bigcommerce'];
const TARGET_NAMES = { shopify: 'Shopify', woocommerce: 'WooCommerce', wix: 'Wix', bigcommerce: 'BigCommerce' };

// group: what the source is, for the matrix sections.
export { SOURCES } from './sources.mjs';
import { SOURCES } from './sources.mjs';

const RANK = { failed: 0, flagged: 1, preserved: 2, ok: 3, 'n/a': 4 };
export const statusRank = (s) => RANK[s];

/** One cell: source × target. */
export function runCell(src, target) {
  const direction = `${src.platform}-to-${target}`;
  if (src.platform === target) return { status: 'n/a', reason: 'same platform' };
  if (!DIRECTIONS.some((d) => d.direction === direction)) return { status: 'n/a', reason: 'no such direction' };
  const opts = { direction, expectPlatform: src.platform, ...(src.opts || {}) };
  if (src.companion) opts.categoriesCsv = read(src.companion);
  if (src.knowledge) opts.knowledge = { formats: [...loadReferenceFormatsSync(), ...src.knowledge.map((rel) => JSON.parse(read(rel)))] };
  const r = convert(read(src.file), opts);
  if (!r.ok) {
    const code = r.errors?.[0]?.code ?? 'unknown';
    if (/^impossible_/.test(code)) return { status: 'n/a', reason: code };
    return { status: 'failed', reason: code };
  }
  const preserved = r.preserved?.fields?.length ?? 0;
  const flags = [...new Set([...r.losses.map((l) => l.code), ...r.warnings.map((w) => w.code)])].sort();
  const status = flags.length ? 'flagged' : preserved ? 'preserved' : 'ok';
  return {
    status, preserved, flagged: flags.length,
    units: r.counts.outputUnits, rows: r.counts.outputRows,
    reason: flags.length ? flags.join(', ') : preserved ? r.preserved.fields.map((f) => f.field).join(', ') : '',
    source: r.sourceFormat, columns: r.headers,
  };
}

/** The whole matrix: { [sourceId]: { [target]: cell } }. */
export function computeMatrix() {
  const out = {};
  for (const src of SOURCES) {
    out[src.id] = {};
    for (const t of TARGETS) out[src.id][t] = runCell(src, t);
  }
  return out;
}

/** The snapshot the suite guards (no column lists: those go to the doc). */
export function snapshotOf(matrix) {
  return Object.fromEntries(Object.entries(matrix).map(([id, row]) => [id, Object.fromEntries(Object.entries(row).map(([t, c]) => [t, { status: c.status, preserved: c.preserved ?? 0, flagged: c.flagged ?? 0, units: c.units ?? 0, reason: c.reason ?? '' }]))]));
}

const ICON = { ok: '✅ ok', preserved: '🟦 preserved', flagged: '🟨 flagged', failed: '❌ failed', 'n/a': '— n/a' };

/** docs/phase2-conversion-matrix.md */
export function renderMarkdown(matrix) {
  const lines = [];
  const cells = Object.values(matrix).flatMap((row) => Object.values(row));
  const count = (s) => cells.filter((c) => c.status === s).length;
  lines.push('# Phase 2 — sites × platforms conversion matrix', '');
  lines.push('> Generated by `node scripts/bench.mjs` from the saved fixtures (no live site, no API, no provider). Guarded by `test/bench.test.mjs`: a cell may not regress (ok → flagged/failed…) and this file must match the engine — regenerate deliberately when a change is intended.', '');
  lines.push('Legend: **ok** converted cleanly · **preserved** converted, source data with no canon field kept and listed (step 4 panel) · **flagged** converted, the user is told something (a loss the target cannot carry, or a notice) · **failed** nothing usable came out · **n/a** the direction does not exist or the target cannot take this entity (not a defect). In each cell: `units` exported · `P` preserved fields · `F` distinct flags.', '');
  lines.push(`**Summary — ${cells.length} cells:** ${count('ok')} ok · ${count('preserved')} preserved · ${count('flagged')} flagged · ${count('failed')} failed · ${count('n/a')} n/a.`, '');
  for (const group of [...new Set(SOURCES.map((s) => s.group))]) {
    lines.push(`## ${group}`, '');
    lines.push('| Source | Format detected | ' + TARGETS.map((t) => TARGET_NAMES[t]).join(' | ') + ' |');
    lines.push('|---|---|' + TARGETS.map(() => '---').join('|') + '|');
    for (const src of SOURCES.filter((s) => s.group === group)) {
      const row = matrix[src.id];
      const fmt = Object.values(row).find((c) => c.source)?.source ?? '—';
      lines.push(`| ${src.label} | \`${fmt}\` | ` + TARGETS.map((t) => {
        const c = row[t];
        if (c.status === 'n/a') return `— n/a (${c.reason})`;
        if (c.status === 'failed') return `❌ failed (\`${c.reason}\`)`;
        return `${ICON[c.status]} · ${c.units}u · P${c.preserved} · F${c.flagged}`;
      }).join(' | ') + ' |');
    }
    lines.push('');
    // reasons, per non-ok cell
    const notes = [];
    for (const src of SOURCES.filter((s) => s.group === group)) for (const t of TARGETS) {
      const c = matrix[src.id][t];
      if (c.status === 'flagged') notes.push(`- ${src.label} → ${t}: flags \`${c.reason}\``);
      else if (c.status === 'preserved') notes.push(`- ${src.label} → ${t}: preserved ${c.reason}`);
      else if (c.status === 'failed') notes.push(`- ${src.label} → ${t}: **failed** \`${c.reason}\``);
    }
    if (notes.length) lines.push('<details><summary>Reasons</summary>', '', ...notes, '', '</details>', '');
  }
  lines.push('## Output columns per target — to verify against the current official template', '');
  lines.push('No official platform template was fetched in this phase (a separate verification pass). Every column below is what the serialisers emitted on this bench, listed so that pass has an exact checklist; **each is "to verify against the current official template"** — none was re-checked here.', '');
  for (const t of TARGETS) {
    const cols = new Set();
    for (const row of Object.values(matrix)) for (const c of row[t] ? [row[t]] : []) for (const h of c.columns || []) cols.add(h);
    lines.push(`- **${t}** (${cols.size}): ${[...cols].map((h) => '`' + h + '`').join(', ')}`);
  }
  lines.push('');
  return lines.join('\n');
}
